if (!class_exists('ChorusPDF')) {
    class ChorusPDF extends FPDF
    {
        public $brandPrimary = [74, 107, 93];
        public $brandAccent = [168, 144, 98];
        public $brandText = [26, 54, 45];
        public $brandMuted = [138, 158, 148];

        public function contentWidth()
        {
            return $this->GetPageWidth() - $this->lMargin - $this->rMargin;
        }

        public function Footer()
        {
            $this->SetY(-15);
            if (file_exists(CHORUS_FONT_DIR . 'Poppins-MediumItalic.php')) {
                $this->SetFont('Poppins-MediumItalic', '', 8);
            } else {
                $this->SetFont('Arial', 'I', 8);
            }
            $this->SetTextColor($this->brandMuted[0], $this->brandMuted[1], $this->brandMuted[2]);
            $this->Cell(0, 6, 'Generated by Chorus Studio Management System - ' . date('d F Y, H:i'), 0, 0, 'C');
            $this->SetX($this->lMargin);
            $this->Cell(0, 6, 'Page ' . $this->PageNo() . '/{nb}', 0, 0, 'R');
        }

        public function MultiCellRow($w, $data, $lineHeight = 6, $aligns = [])
        {
            $nb = 0;
            for ($i = 0; $i < count($data); $i++) {
                $a = $data[$i] === null ? '' : (string)$data[$i];
                $nb = max($nb, $this->NbLines($w[$i], $a));
            }
            $hTotal = $lineHeight * $nb;
            $this->CheckPageBreak($hTotal);
            $xStart = $this->GetX();
            $yStart = $this->GetY();

            for ($i = 0; $i < count($data); $i++) {
                $x = $this->GetX();
                $y = $this->GetY();
                $this->Rect($x, $y, $w[$i], $hTotal);
                $align = $aligns[$i] ?? 'L';
                $this->MultiCell($w[$i], $lineHeight, $data[$i], 0, $align);
                $this->SetXY($x + $w[$i], $y);
            }
            $this->SetXY($xStart, $yStart + $hTotal);
        }

        public function CheckPageBreak($h)
        {
            if ($this->GetY() + $h > $this->h - 25) {
                $this->AddPage();
                $this->TableHeader();
            }
        }

        public function NbLines($w, $txt)
        {
            $cw = &$this->CurrentFont['cw'];
            if ($w == 0) $w = $this->w - $this->rMargin - $this->x;
            $wmax = ($w - 2 * $this->cMargin) * 1000 / $this->FontSize;
            $s = str_replace("\r", '', (string)$txt);
            $nb = strlen($s);
            if ($nb > 0 && $s[$nb - 1] == "\n") $nb--;
            $sep = -1;
            $i = 0;
            $j = 0;
            $l = 0;
            $nl = 1;
            while ($i < $nb) {
                $c = $s[$i];
                if ($c == "\n") {
                    $i++;
                    $sep = -1;
                    $j = $i;
                    $l = 0;
                    $nl++;
                    continue;
                }
                if ($c == ' ') $sep = $i;
                $l += $cw[$c] ?? 0;
                if ($l > $wmax) {
                    if ($sep == -1) {
                        if ($i == $j) $i++;
                    } else {
                        $i = $sep + 1;
                    }
                    $sep = -1;
                    $j = $i;
                    $l = 0;
                    $nl++;
                } else {
                    $i++;
                }
            }
            return $nl;
        }

        public function TableHeader()
        {
            if (file_exists(CHORUS_FONT_DIR . 'Poppins-SemiBold.php')) {
                $this->SetFont('Poppins-SemiBold', '', 10);
            } else {
                $this->SetFont('Arial', 'B', 10);
            }
            $this->SetFillColor($this->brandPrimary[0], $this->brandPrimary[1], $this->brandPrimary[2]);
            $this->SetTextColor(255, 255, 255);
            $this->SetDrawColor($this->brandPrimary[0], $this->brandPrimary[1], $this->brandPrimary[2]);
            
            $this->Cell(30, 8, 'Tanggal', 1, 0, 'C', true);
            $this->Cell(60, 8, 'Lagu', 1, 0, 'C', true);
            $this->Cell(0, 8, 'Catatan', 1, 1, 'C', true);
            
            if (file_exists(CHORUS_FONT_DIR . 'Poppins-Medium.php')) {
                $this->SetFont('Poppins-Medium', '', 10);
            } else {
                $this->SetFont('Arial', '', 10);
            }
            $this->SetTextColor($this->brandText[0], $this->brandText[1], $this->brandText[2]);
            $this->SetDrawColor(220, 220, 220);
        }
    }
}

function chorus_safe_filename($name)
{
    return preg_replace('/[^A-Za-z0-9_\-]/', '_', $name);
}

function build_report_pdf(PDO $pdo, int $id_murid, int $tahun, int $bulan)
{
    $m = $pdo->prepare('SELECT * FROM murid WHERE id=?');
    $m->execute([$id_murid]);
    $murid = $m->fetch();
    if (!$murid) {
        return null;
    }

    $r = $pdo->prepare('SELECT * FROM refleksi WHERE id_murid=? AND tahun=? AND bulan=?');
    $r->execute([$id_murid, $tahun, $bulan]);
    $ref = $r->fetch();

    $p = $pdo->prepare('SELECT p.tanggal, l.judul as lagu_judul, p.catatan
                        FROM pertemuan p
                        LEFT JOIN lagu l ON p.id_lagu=l.id_lagu
                        WHERE p.id_murid=? AND YEAR(p.tanggal)=? AND MONTH(p.tanggal)=?
                        ORDER BY p.tanggal ASC');
    $p->execute([$id_murid, $tahun, $bulan]);
    $pertemuan = $p->fetchAll();

    $pdf = new ChorusPDF('P', 'mm', 'A4');
    if (file_exists(CHORUS_FONT_DIR . 'Poppins-Medium.php')) {
        $pdf->AddFont('Poppins-Medium', '', 'Poppins-Medium.php');
    }
    if (file_exists(CHORUS_FONT_DIR . 'Poppins-SemiBold.php')) {
        $pdf->AddFont('Poppins-SemiBold', '', 'Poppins-SemiBold.php');
    }
    if (file_exists(CHORUS_FONT_DIR . 'Poppins-MediumItalic.php')) {
        $pdf->AddFont('Poppins-MediumItalic', '', 'Poppins-MediumItalic.php');
    }

    $pdf->AliasNbPages();
    $pdf->SetAutoPageBreak(true, 25);
    $pdf->AddPage();

    $logoPath = CHORUS_ROOT . '/assets/img/logo-w.png';
    $wmPath = CHORUS_ROOT . '/assets/img/faded-logo.png';

    // Header Bar
    $pdf->SetFillColor($pdf->brandPrimary[0], $pdf->brandPrimary[1], $pdf->brandPrimary[2]);
    $pdf->Rect(0, 0, $pdf->GetPageWidth(), 40, 'F');

    if (file_exists($logoPath)) {
        $pdf->Image($logoPath, 15, 8, 24, 24);
    }

    $pdf->SetXY(45, 10);
    if (file_exists(CHORUS_FONT_DIR . 'Poppins-SemiBold.php')) {
        $pdf->SetFont('Poppins-SemiBold', '', 20);
    } else {
        $pdf->SetFont('Arial', 'B', 20);
    }
    $pdf->SetTextColor(255, 255, 255);
    $pdf->Cell(0, 10, 'CHORUS STUDIO', 0, 1, 'L');

    $pdf->SetX(45);
    if (file_exists(CHORUS_FONT_DIR . 'Poppins-MediumItalic.php')) {
        $pdf->SetFont('Poppins-MediumItalic', '', 10);
    } else {
        $pdf->SetFont('Arial', 'I', 10);
    }
    $pdf->SetTextColor(200, 220, 210);
    $pdf->Cell(0, 5, '"Your all rounder for Vocal Class music and Recording."', 0, 1, 'L');

    $pdf->SetXY(45, 26);
    if (file_exists(CHORUS_FONT_DIR . 'Poppins-Medium.php')) {
        $pdf->SetFont('Poppins-Medium', '', 9);
    } else {
        $pdf->SetFont('Arial', '', 9);
    }
    $pdf->SetTextColor(255, 255, 255);
    $phoneIcon = CHORUS_ROOT . '/assets/icon-phone.png';
    $igIcon = CHORUS_ROOT . '/assets/icon-instagram.png';
    
    $pdf->SetX(45);
    // Draw simple icons or text if icons not found
    $pdf->Cell(35, 5, 'Ph: 0896-8704-6786', 0, 0, 'L');
    $pdf->Cell(0, 5, 'IG: @chorusstudio_', 0, 1, 'L');

    // Watermark
    if ($wmPath && file_exists($wmPath)) {
        $pdfW = $pdf->contentWidth();
        $wmWidthMm = $pdfW * 0.6;
        list($origW, $origH) = getimagesize($wmPath);
        $ratio = $origH / $origW;
        $wmHeightMm = $wmWidthMm * $ratio;
        $x = ($pdf->GetPageWidth() - $wmWidthMm) / 2;
        $y = ($pdf->GetPageHeight() - $wmHeightMm) / 2 + 20;
        $pdf->Image($wmPath, $x, $y, $wmWidthMm, $wmHeightMm, '', '', '', false, 300, '', false, false, 0, 'C');
    }

    // Student Info Section
    $pdf->SetY(50);
    $pdf->SetTextColor($pdf->brandText[0], $pdf->brandText[1], $pdf->brandText[2]);
    
    if (file_exists(CHORUS_FONT_DIR . 'Poppins-SemiBold.php')) {
        $pdf->SetFont('Poppins-SemiBold', '', 28);
    } else {
        $pdf->SetFont('Arial', 'B', 24);
    }
    $pdf->Cell(130, 12, strtoupper($murid['nama']), 0, 1, 'L');

    if (file_exists(CHORUS_FONT_DIR . 'Poppins-MediumItalic.php')) {
        $pdf->SetFont('Poppins-MediumItalic', '', 12);
    } else {
        $pdf->SetFont('Arial', 'I', 12);
    }
    $pdf->SetTextColor($pdf->brandMuted[0], $pdf->brandMuted[1], $pdf->brandMuted[2]);
    $monthYear = date('F Y', strtotime("$tahun-$bulan-01"));
    $pdf->Cell(130, 8, "Monthly Progress Report - $monthYear", 0, 1, 'L');

    $fotoX = 150;
    $fotoY = 50;
    $fotoW = 45;
    if ($murid['foto'] && file_exists(CHORUS_ROOT . '/' . $murid['foto'])) {
        list($pw, $ph) = getimagesize(CHORUS_ROOT . '/' . $murid['foto']);
        $ratio = min($fotoW / $pw, 55 / $ph);
        $finalW = $pw * $ratio;
        $finalH = $ph * $ratio;
        // Shadow effect for photo
        $pdf->SetFillColor(240, 240, 240);
        $pdf->Rect($fotoX + 1, $fotoY + 1, $finalW, $finalH, 'F');
        $pdf->Image(CHORUS_ROOT . '/' . $murid['foto'], $fotoX, $fotoY, $finalW, $finalH);
        $pdf->SetDrawColor($pdf->brandAccent[0], $pdf->brandAccent[1], $pdf->brandAccent[2]);
        $pdf->SetLineWidth(0.5);
        $pdf->Rect($fotoX, $fotoY, $finalW, $finalH, 'D');
    }

    $pdf->SetY(75);
    $cnt = $pdo->prepare('SELECT COUNT(*) FROM pertemuan WHERE id_murid=? AND YEAR(tanggal)=? AND MONTH(tanggal)=?');
    $cnt->execute([$id_murid, $tahun, $bulan]);
    $count = $cnt->fetchColumn();

    if (file_exists(CHORUS_FONT_DIR . 'Poppins-Medium.php')) {
        $pdf->SetFont('Poppins-Medium', '', 10);
    } else {
        $pdf->SetFont('Arial', '', 10);
    }
    $pdf->SetTextColor($pdf->brandText[0], $pdf->brandText[1], $pdf->brandText[2]);
    $pdf->Cell(40, 6, 'Total Pertemuan:', 0, 0);
    if (file_exists(CHORUS_FONT_DIR . 'Poppins-SemiBold.php')) {
        $pdf->SetFont('Poppins-SemiBold', '', 10);
    } else {
        $pdf->SetFont('Arial', 'B', 10);
    }
    $pdf->Cell(0, 6, $count . ' kali', 0, 1);

    $pdf->Ln(10);
    
    // Helper function for section headers
    $drawSection = function($title, $content) use ($pdf) {
        if (file_exists(CHORUS_FONT_DIR . 'Poppins-SemiBold.php')) {
            $pdf->SetFont('Poppins-SemiBold', '', 12);
        } else {
            $pdf->SetFont('Arial', 'B', 12);
        }
        $pdf->SetTextColor($pdf->brandPrimary[0], $pdf->brandPrimary[1], $pdf->brandPrimary[2]);
        $pdf->Cell(0, 8, strtoupper($title), 0, 1);
        
        $pdf->SetDrawColor($pdf->brandAccent[0], $pdf->brandAccent[1], $pdf->brandAccent[2]);
        $pdf->SetLineWidth(0.8);
        $pdf->Line($pdf->GetX(), $pdf->GetY(), $pdf->GetX() + 20, $pdf->GetY());
        $pdf->Ln(3);
        
        if (file_exists(CHORUS_FONT_DIR . 'Poppins-Medium.php')) {
            $pdf->SetFont('Poppins-Medium', '', 11);
        } else {
            $pdf->SetFont('Arial', '', 11);
        }
        $pdf->SetTextColor($pdf->brandText[0], $pdf->brandText[1], $pdf->brandText[2]);
        $pdf->MultiCell(0, 6, $content ?: '-');
        $pdf->Ln(6);
    };

    $drawSection('Refleksi', $ref['refleksi'] ?? '-');
    $drawSection('Rencana Perbaikan', $ref['rencana_perbaikan'] ?? '-');
    $drawSection('Saran', $ref['saran'] ?? '-');

    $pdf->Ln(4);
    if (file_exists(CHORUS_FONT_DIR . 'Poppins-SemiBold.php')) {
        $pdf->SetFont('Poppins-SemiBold', '', 12);
    } else {
        $pdf->SetFont('Arial', 'B', 12);
    }
    $pdf->SetTextColor($pdf->brandPrimary[0], $pdf->brandPrimary[1], $pdf->brandPrimary[2]);
    $pdf->Cell(0, 8, 'DETAIL PERTEMUAN', 0, 1);
    $pdf->SetDrawColor($pdf->brandAccent[0], $pdf->brandAccent[1], $pdf->brandAccent[2]);
    $pdf->Line($pdf->GetX(), $pdf->GetY(), $pdf->GetX() + 20, $pdf->GetY());
    $pdf->Ln(3);
    
    $pdf->TableHeader();
    $pdf->SetDrawColor(230, 230, 230);
    foreach ($pertemuan as $pp) {
        $tanggal = date('d/m/Y', strtotime($pp['tanggal']));
        $lagu = $pp['lagu_judul'] ?: '-';
        $catatan = $pp['catatan'] ?: '-';
        $pdf->MultiCellRow([30, 60, ($pdf->contentWidth() - 30 - 60)], [$tanggal, $lagu, $catatan], 6, ['C', 'L', 'L']);
    }

    $safeName = chorus_safe_filename($murid['nama']);
    $monthName = date('F', strtotime("$tahun-$bulan-01"));
    $fileName = sprintf('Laporan_%s_%s_%d.pdf', $safeName, $monthName, $tahun);

    return [
        'pdf' => $pdf,
        'murid' => $murid,
        'file_name' => $fileName,
    ];
}
